using SonarAnalyzer.TestFramework.Extensions;

namespace SonarAnalyzer.ShimLayer.Generator.Strategies.Test;

[TestClass]
public class DelegateStrategyTest
{
    private static readonly StrategyModel Model = new()
    {
        { typeof(ITypeSymbol), new InterfaceWrapStrategy(typeof(ITypeSymbol), typeof(object), []) },
        { typeof(IDiscardSymbol), new InterfaceWrapStrategy(typeof(IDiscardSymbol), typeof(object), []) },
    };

    private delegate IDiscardSymbol Creator(ITypeSymbol type);
    private delegate bool Handler(ITypeSymbol type, ref int count, out string message, params object[] args);
    private delegate void WrappedRefHandler(ref ITypeSymbol type);

    [TestMethod]
    public void TypeSnippet() =>
        new DelegateStrategy(typeof(Creator)).TypeSnippet.Should().Be("CreatorWrapper");

    [TestMethod]
    public void Generate_WrappedTypes() =>
        new DelegateStrategy(typeof(Creator)).Generate(Model).Should().BeIgnoringLineEndings(
            """
            //<auto-generated/>
            /*
             * SonarAnalyzer for .NET
             * Copyright (C) SonarSource Sàrl
             * mailto:info AT sonarsource DOT com
             *
             * You can redistribute and/or modify this program under the terms of
             * the Sonar Source-Available License Version 1, as published by SonarSource Sàrl.
             *
             * This program is distributed in the hope that it will be useful,
             * but WITHOUT ANY WARRANTY; without even the implied warranty of
             * MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.
             * See the Sonar Source-Available License for more details.
             *
             * You should have received a copy of the Sonar Source-Available License
             * along with this program; if not, see https://sonarsource.com/license/ssal/
             */

            namespace SonarAnalyzer.ShimLayer;

            public delegate IDiscardSymbolWrapper CreatorWrapper(ITypeSymbolWrapper type);
            """);

    [TestMethod]
    public void Generate_RefOutParams() =>
        new DelegateStrategy(typeof(Handler)).Generate(Model).Should().BeIgnoringLineEndings(
            """
            //<auto-generated/>
            /*
             * SonarAnalyzer for .NET
             * Copyright (C) SonarSource Sàrl
             * mailto:info AT sonarsource DOT com
             *
             * You can redistribute and/or modify this program under the terms of
             * the Sonar Source-Available License Version 1, as published by SonarSource Sàrl.
             *
             * This program is distributed in the hope that it will be useful,
             * but WITHOUT ANY WARRANTY; without even the implied warranty of
             * MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.
             * See the Sonar Source-Available License for more details.
             *
             * You should have received a copy of the Sonar Source-Available License
             * along with this program; if not, see https://sonarsource.com/license/ssal/
             */

            namespace SonarAnalyzer.ShimLayer;

            public delegate bool HandlerWrapper(ITypeSymbolWrapper type, ref int count, out string message, params object[] args);
            """);

    [TestMethod]
    public void Generate_RefOfWrappedType_NotSupported() =>
        new DelegateStrategy(typeof(WrappedRefHandler))
            .Invoking(x => x.Generate(Model))
            .Should().Throw<NotSupportedException>()
            .WithMessage("*by-ref parameter 'type' of wrapped type ITypeSymbol is not supported.");
}
