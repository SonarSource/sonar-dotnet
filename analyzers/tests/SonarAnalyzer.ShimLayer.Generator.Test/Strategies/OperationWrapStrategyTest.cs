using Microsoft.CodeAnalysis.Operations;
using SonarAnalyzer.TestFramework.Extensions;

namespace SonarAnalyzer.ShimLayer.Generator.Strategies.Test;

[TestClass]
public class OperationWrapStrategyTest
{
    [TestMethod]
    public void Generate_Empty()
    {
        var sut = new OperationWrapStrategy(typeof(IFieldInitializerOperation), []);
        var result = sut.Generate([]);
        result.Should().BeIgnoringLineEndings(
            """
            //<auto-generated/>
            /*
             * SonarAnalyzer for .NET
             * Copyright (C) SonarSource Sàrl
             * mailto:info AT sonarsource DOT com
             *
             * You can redistribute and/or modify this program under the terms of
             * the Sonar Source-Available License Version 1, as published by SonarSource Sàrl.
             *
             * This program is distributed in the hope that it will be useful,
             * but WITHOUT ANY WARRANTY; without even the implied warranty of
             * MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.
             * See the Sonar Source-Available License for more details.
             *
             * You should have received a copy of the Sonar Source-Available License
             * along with this program; if not, see https://sonarsource.com/license/ssal/
             */

            using Microsoft.CodeAnalysis;
            using Microsoft.CodeAnalysis.CSharp;
            using Microsoft.CodeAnalysis.CSharp.Syntax;
            using Microsoft.CodeAnalysis.Text;
            using System;
            using System.Collections.Immutable;

            namespace SonarAnalyzer.ShimLayer;

            internal readonly partial struct IFieldInitializerOperationWrapper : IOperationWrapper
            {
                public const string WrappedTypeName = "Microsoft.CodeAnalysis.Operations.IFieldInitializerOperation";
                private static readonly Type WrappedType;

                private readonly IOperation operation;

                static IFieldInitializerOperationWrapper()
                {
                    WrappedType = TypeRegister.LatestType(typeof(IFieldInitializerOperationWrapper));
                }

                private IFieldInitializerOperationWrapper(IOperation operation) =>
                    this.operation = operation;

                [Obsolete("Use WrappedInstance instead")]
                public IOperation WrappedOperation => this.operation;

                public IOperation WrappedInstance => this.operation;

                [Obsolete("Use From instead")]
                public static IFieldInitializerOperationWrapper FromOperation(IOperation operation) =>
                    From(operation);

                public static IFieldInitializerOperationWrapper From(IOperation operation)
                {
                    if (operation is null)
                    {
                        return default;
                    }
                    else if (IsInstance(operation))
                    {
                        return new IFieldInitializerOperationWrapper(operation);
                    }
                    else
                    {
                        throw new InvalidCastException($"Cannot cast '{operation.GetType().FullName}' to '{WrappedTypeName}'");
                    }
                }

                public static bool IsInstance(IOperation operation) =>
                    operation is not null && LightupHelpers.CanWrapOperation(operation, WrappedType);

            }
            """);
    }

    [TestMethod]
    public void Generate_WrapperToWrapperConversions()
    {
        var sut = new OperationWrapStrategy(typeof(IFieldReferenceOperation), []);
        var model = new Dictionary<Type, Strategy>
        {
            { typeof(IFieldReferenceOperation), sut },
            { typeof(IMemberReferenceOperation), new OperationWrapStrategy(typeof(IMemberReferenceOperation), []) },
            { typeof(IOperation), new OperationExtendStrategy(typeof(IOperation), []) },
        };
        var result = sut.Generate(new(model));
        result.Should().BeIgnoringLineEndings(
            """
            //<auto-generated/>
            /*
             * SonarAnalyzer for .NET
             * Copyright (C) SonarSource Sàrl
             * mailto:info AT sonarsource DOT com
             *
             * You can redistribute and/or modify this program under the terms of
             * the Sonar Source-Available License Version 1, as published by SonarSource Sàrl.
             *
             * This program is distributed in the hope that it will be useful,
             * but WITHOUT ANY WARRANTY; without even the implied warranty of
             * MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.
             * See the Sonar Source-Available License for more details.
             *
             * You should have received a copy of the Sonar Source-Available License
             * along with this program; if not, see https://sonarsource.com/license/ssal/
             */

            using Microsoft.CodeAnalysis;
            using Microsoft.CodeAnalysis.CSharp;
            using Microsoft.CodeAnalysis.CSharp.Syntax;
            using Microsoft.CodeAnalysis.Text;
            using System;
            using System.Collections.Immutable;

            namespace SonarAnalyzer.ShimLayer;

            internal readonly partial struct IFieldReferenceOperationWrapper : IOperationWrapper
            {
                public const string WrappedTypeName = "Microsoft.CodeAnalysis.Operations.IFieldReferenceOperation";
                private static readonly Type WrappedType;

                private readonly IOperation operation;

                static IFieldReferenceOperationWrapper()
                {
                    WrappedType = TypeRegister.LatestType(typeof(IFieldReferenceOperationWrapper));
                }

                private IFieldReferenceOperationWrapper(IOperation operation) =>
                    this.operation = operation;

                [Obsolete("Use WrappedInstance instead")]
                public IOperation WrappedOperation => this.operation;

                public IOperation WrappedInstance => this.operation;

                [Obsolete("Use From instead")]
                public static IFieldReferenceOperationWrapper FromOperation(IOperation operation) =>
                    From(operation);

                public static IFieldReferenceOperationWrapper From(IOperation operation)
                {
                    if (operation is null)
                    {
                        return default;
                    }
                    else if (IsInstance(operation))
                    {
                        return new IFieldReferenceOperationWrapper(operation);
                    }
                    else
                    {
                        throw new InvalidCastException($"Cannot cast '{operation.GetType().FullName}' to '{WrappedTypeName}'");
                    }
                }

                public static bool IsInstance(IOperation operation) =>
                    operation is not null && LightupHelpers.CanWrapOperation(operation, WrappedType);

                public static implicit operator IMemberReferenceOperationWrapper(IFieldReferenceOperationWrapper up) => IMemberReferenceOperationWrapper.From(up.WrappedInstance);
                public static explicit operator IFieldReferenceOperationWrapper(IMemberReferenceOperationWrapper down) => IFieldReferenceOperationWrapper.From(down.WrappedInstance);

            }
            """);
    }
