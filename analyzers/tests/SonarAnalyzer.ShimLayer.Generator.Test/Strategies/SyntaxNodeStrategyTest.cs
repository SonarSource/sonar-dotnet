using Microsoft.CodeAnalysis.CSharp.Syntax;
using SonarAnalyzer.TestFramework.Extensions;

namespace SonarAnalyzer.ShimLayer.Generator.Strategies.Test;

[TestClass]
public class SyntaxNodeStrategyTest
{
    [TestMethod]
    public void Generate_SyntaxNode()
    {
        var sut = new SyntaxNodeStrategy(
            typeof(SyntaxNode),
            [
                new(typeof(SyntaxNode).GetMember(nameof(SyntaxNode.Parent))[0], true, "ParentAccessor"),  // Existing member, should be ignored
                new(typeof(SyntaxNode).GetMember(nameof(SyntaxNode.ContainsDirective))[0], false, "ContainsDirectiveAccessor"),
            ]);
        var result = sut.Generate(new StrategyModel
        {
            { typeof(RecordDeclarationSyntax), new SyntaxNodeWrapStrategy(typeof(RecordDeclarationSyntax), typeof(TypeDeclarationSyntax), null, []) },
            { typeof(WithExpressionSyntax), new SyntaxNodeWrapStrategy(typeof(WithExpressionSyntax), typeof(ExpressionSyntax), null, []) },
        });
        result.Should().BeIgnoringLineEndings(
            """
            //<auto-generated/>
            /*
             * SonarAnalyzer for .NET
             * Copyright (C) SonarSource Sàrl
             * mailto:info AT sonarsource DOT com
             *
             * You can redistribute and/or modify this program under the terms of
             * the Sonar Source-Available License Version 1, as published by SonarSource Sàrl.
             *
             * This program is distributed in the hope that it will be useful,
             * but WITHOUT ANY WARRANTY; without even the implied warranty of
             * MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.
             * See the Sonar Source-Available License for more details.
             *
             * You should have received a copy of the Sonar Source-Available License
             * along with this program; if not, see https://sonarsource.com/license/ssal/
             */

            namespace SonarAnalyzer.ShimLayer;

            public static class SyntaxNodeShimExtensions
            {
                private static readonly Type WrappedType = typeof(SyntaxNode);

                private static readonly Func<SyntaxNode, int, bool> ContainsDirectiveAccessor = AccessorFactory.CreateMethod<Func<SyntaxNode, int, bool>>(WrappedType, "ContainsDirective");

                extension(SyntaxNode wrappedInstance)
                {
                    public bool ContainsDirective(int rawKind) => ContainsDirectiveAccessor(wrappedInstance, rawKind);

                    public SyntaxNodeAs As => new(wrappedInstance);
                    public SyntaxNodeTo To => new(wrappedInstance);
                }
            }

            public readonly struct SyntaxNodeAs
            {
                private readonly SyntaxNode node;
                internal SyntaxNodeAs(SyntaxNode node) => this.node = node;

                public RecordDeclarationSyntaxWrapper? RecordDeclaration => RecordDeclarationSyntaxWrapper.FromOrDefault(node);
                public WithExpressionSyntaxWrapper? WithExpression => WithExpressionSyntaxWrapper.FromOrDefault(node);
            }

            public readonly struct SyntaxNodeTo
            {
                private readonly SyntaxNode node;
                internal SyntaxNodeTo(SyntaxNode node) => this.node = node;

                public RecordDeclarationSyntaxWrapper RecordDeclaration => RecordDeclarationSyntaxWrapper.From(node);
                public WithExpressionSyntaxWrapper WithExpression => WithExpressionSyntaxWrapper.From(node);
            }
            """);
    }

    [TestMethod]
    public void Generate_SyntaxNode_NoNewMembers_StillEmitsAsAndToGates()
    {
        // Simulates a baseline bump that catches up with every member SyntaxNode currently needs the shim for (no new/passthrough members at all).
        // The As/To gates and SyntaxNodeAs/SyntaxNodeTo structs must still be generated, because every XxxSyntaxWrapper unconditionally forwards to them.
        var sut = new SyntaxNodeStrategy(typeof(SyntaxNode), []);
        var result = sut.Generate(new StrategyModel
        {
            { typeof(RecordDeclarationSyntax), new SyntaxNodeWrapStrategy(typeof(RecordDeclarationSyntax), typeof(TypeDeclarationSyntax), null, []) },
        });
        result.Should().NotBeNull();
        result.Should().Contain("public SyntaxNodeAs As => new(wrappedInstance);");
        result.Should().Contain("public SyntaxNodeTo To => new(wrappedInstance);");
        result.Should().Contain("public RecordDeclarationSyntaxWrapper? RecordDeclaration => RecordDeclarationSyntaxWrapper.FromOrDefault(node);");
        result.Should().Contain("public RecordDeclarationSyntaxWrapper RecordDeclaration => RecordDeclarationSyntaxWrapper.From(node);");
    }

    [TestMethod]
    public void Constructor_WrongType_Throws()
    {
        var sut = () => new SyntaxNodeStrategy(typeof(ExpressionSyntax), []);
        sut.Should().Throw<ArgumentException>().WithMessage("SyntaxNodeStrategy should be used only with SyntaxNode itself.");
    }
}
