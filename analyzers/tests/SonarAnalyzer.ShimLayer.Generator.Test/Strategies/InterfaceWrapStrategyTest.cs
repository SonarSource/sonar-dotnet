using SonarAnalyzer.TestFramework.Extensions;

namespace SonarAnalyzer.ShimLayer.Generator.Strategies.Test;

[TestClass]
public class InterfaceWrapStrategyTest
{
    [TestMethod]
    public void Generate_Members()
    {
        var sut = new InterfaceWrapStrategy(
            typeof(IDiscardSymbol),
            typeof(object),
            [new(typeof(IDiscardSymbol).GetMember(nameof(IDiscardSymbol.Type))[0], false, "TypeAccessor")]);
        var result = sut.Generate([]);
        result.Should().BeIgnoringLineEndings(
            """
            //<auto-generated/>
            /*
             * SonarAnalyzer for .NET
             * Copyright (C) SonarSource Sàrl
             * mailto:info AT sonarsource DOT com
             *
             * You can redistribute and/or modify this program under the terms of
             * the Sonar Source-Available License Version 1, as published by SonarSource Sàrl.
             *
             * This program is distributed in the hope that it will be useful,
             * but WITHOUT ANY WARRANTY; without even the implied warranty of
             * MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.
             * See the Sonar Source-Available License for more details.
             *
             * You should have received a copy of the Sonar Source-Available License
             * along with this program; if not, see https://sonarsource.com/license/ssal/
             */

            namespace SonarAnalyzer.ShimLayer;

            public readonly struct IDiscardSymbolWrapper
            {
                private static readonly Type WrappedType = TypeRegister.LatestType("Microsoft.CodeAnalysis.IDiscardSymbol");
                private static readonly ConcurrentDictionary<Type, bool> CanWrapCache = new();
                private readonly Object wrappedInstance;

                private static readonly Func<Object, ITypeSymbol> TypeAccessor = AccessorFactory.CreateProperty<Func<Object, ITypeSymbol>>(WrappedType, "Type");

                private IDiscardSymbolWrapper(Object wrappedInstance) =>
                    this.wrappedInstance = wrappedInstance;

                public Object WrappedInstance => wrappedInstance;

                public ITypeSymbol Type => (ITypeSymbol)TypeAccessor(wrappedInstance);

                public static IDiscardSymbolWrapper From(object instance)
                {
                    if (instance is null)
                    {
                        return default;
                    }
                    else if (IsInstance(instance))
                    {
                        return new IDiscardSymbolWrapper((Object)instance);
                    }
                    else
                    {
                        throw new InvalidCastException($"Cannot cast '{instance.GetType().FullName}' to 'Microsoft.CodeAnalysis.IDiscardSymbol'");
                    }
                }

                public static bool IsInstance(object instance) =>
                    WrappedType.CanWrap(CanWrapCache, instance);
            }
            """);
    }
}
